# Standard column names used throughout this project
STANDARD_VITALS = [
    "heart_rate",
    "spo2",
    "respiratory_rate",
    "temperature",
    "systolic_bp",
    "diastolic_bp",
]

# CinC 2019 PSV files use these column names
CINC2019_COLUMN_MAP = {
    "HR":    "heart_rate",
    "O2Sat": "spo2",
    "Resp":  "respiratory_rate",
    "Temp":  "temperature",
    "SBP":   "systolic_bp",
    "DBP":   "diastolic_bp",
    "MAP":   "mean_arterial_pressure",    # extra — keep if present
    "EtCO2": "etco2",                     # extra — keep if present
}

# Synthetic data already uses our standard column names


# ─────────────────────────────────────────────────────────────────────────────
# LOADER 1: CinC 2019 (Primary Dataset)
# ─────────────────────────────────────────────────────────────────────────────

def load_cinc2019(
    data_dir: str,
    max_patients: Optional[int] = None,
    verbose: bool = True,
) -> pd.DataFrame:
    """
    Load the PhysioNet CinC Challenge 2019 dataset from PSV files.

    ⚠️  This is ADULT ICU data, not neonatal data.
    Use it only for prototype development as a "reference ICU dataset".

    Parameters
    ----------
    data_dir : str
        Path to the directory containing .psv files (e.g., training_setA/).
    max_patients : int, optional
        Limit number of patients loaded (useful for quick testing).
    verbose : bool
        Whether to log progress.

    Returns
    -------
    pd.DataFrame
        Combined DataFrame with standardized column names:
        timestamp (reconstructed from ICULOS), patient_id, vital signs,
        SepsisLabel (renamed to deterioration_label).

    Columns output:
        patient_id, iculos, heart_rate, spo2, respiratory_rate,
        temperature, systolic_bp, diastolic_bp, deterioration_label, age, gender
    """
    psv_files = sorted(glob.glob(os.path.join(data_dir, "*.psv")))

    if not psv_files:
        logger.error(
            f"No .psv files found in {data_dir}. "
            f"Please download CinC 2019 data from: "
            f"https://physionet.org/content/challenge-2019/1.0.0/"
        )
        raise FileNotFoundError(
            f"CinC 2019 data not found in {data_dir}. "
            f"Download from https://physionet.org/content/challenge-2019/1.0.0/"
        )

    if max_patients is not None:
        psv_files = psv_files[:max_patients]

    if verbose:
        logger.info(f"Loading CinC 2019 data from {data_dir}")
        logger.info(f"Found {len(psv_files)} patient files")
        logger.info("⚠️  REMINDER: This is ADULT ICU data — not neonatal.")

    all_patients = []

    for fpath in psv_files:
        try:
            df = pd.read_csv(fpath, sep="|")
        except Exception as e:
            logger.warning(f"Could not load {fpath}: {e}")
            continue

        # Extract patient ID from filename (e.g., p000001.psv → p000001)
        patient_id = os.path.splitext(os.path.basename(fpath))[0]
        df["patient_id"] = patient_id

        # Rename columns to our standard schema
        df = df.rename(columns=CINC2019_COLUMN_MAP)

        # Rename the label column
        if "SepsisLabel" in df.columns:
            df = df.rename(columns={"SepsisLabel": "deterioration_label"})
        else:
            df["deterioration_label"] = np.nan

        # Add metadata columns
        df["data_source"] = "CINC2019_ADULT_ICU"
        df["data_warning"] = (
            "ADULT_ICU_REFERENCE_DATA_NOT_NEONATAL_NOT_FOR_CLINICAL_USE"
        )

        all_patients.append(df)

    if not all_patients:
        raise ValueError("No patient data could be loaded.")

    combined = pd.concat(all_patients, ignore_index=True)

    # ICULOS (ICU Length of Stay) is in hours — use it as a time proxy
    if "ICULOS" in combined.columns:
        combined = combined.rename(columns={"ICULOS": "iculos_hours"})

    if verbose:
        logger.info(f"Loaded {combined['patient_id'].nunique()} patients")
        logger.info(f"Total rows: {len(combined):,}")
        if "deterioration_label" in combined.columns:
            n_events = combined["deterioration_label"].sum()
            logger.info(
                f"Sepsis events: {n_events:.0f} "
                f"({n_events / len(combined) * 100:.1f}%)"
            )

    return combined


# ─────────────────────────────────────────────────────────────────────────────
# LOADER 2: PICS Database (Neonatal Waveforms)
# ─────────────────────────────────────────────────────────────────────────────

def load_pics_database(
    data_dir: str,
    derive_hr: bool = True,
    derive_rr: bool = True,
    verbose: bool = True,
) -> pd.DataFrame:
    """
    Load the Preterm Infant Cardio-Respiratory Signals (PICS) database.

    ✅ This is AUTHENTIC NEONATAL data (10 preterm infants).

    Requires the `wfdb` library: pip install wfdb

    The PICS database contains:
    - ECG signals (500 or 250 Hz)
    - Respiration signals (50 Hz)
    - Bradycardia annotations (atr files)

    This function:
    - Reads ECG and respiration WFDB records
    - Derives a coarse Heart Rate from RR intervals (qrsc annotations)
    - Derives a coarse Respiratory Rate from respiration annotations
    - Aligns with bradycardia annotations to create a label

    Parameters
    ----------
    data_dir : str
        Path to directory containing PICS WFDB files (.hea, .dat, .qrsc, .atr).
    derive_hr : bool
        Whether to derive HR from R-peak annotations.
    derive_rr : bool
        Whether to derive RR from respiration peak annotations.
    verbose : bool
        Whether to log progress.

    Returns
    -------
    pd.DataFrame
        DataFrame with columns:
        patient_id, window_index, heart_rate (derived), respiratory_rate (derived),
        bradycardia_label

    Note
    ----
    SpO2, Temperature, and Blood Pressure are NOT available in this dataset.
    Those columns will be NaN.
    """
    try:
        import wfdb
    except ImportError:
        raise ImportError(
            "The `wfdb` library is required to load PICS data. "
            "Install with: pip install wfdb"
        )

    if not os.path.isdir(data_dir):
        logger.error(
            f"PICS data directory not found: {data_dir}\n"
            f"Download from: https://physionet.org/content/picsdb/1.0.0/"
        )
        raise FileNotFoundError(
            f"PICS data directory not found: {data_dir}"
        )

    if verbose:
        logger.info(f"Loading PICS neonatal waveform data from {data_dir}")
        logger.info("✅ This is authentic neonatal data (10 preterm infants).")

    all_infants = []

    for infant_num in range(1, 11):
        ecg_record_name = f"infant{infant_num}_ecg"
        resp_record_name = f"infant{infant_num}_resp"
        ecg_path = os.path.join(data_dir, ecg_record_name)
        resp_path = os.path.join(data_dir, resp_record_name)

        if not os.path.exists(ecg_path + ".hea"):
            if verbose:
                logger.warning(f"Infant {infant_num} ECG record not found, skipping.")
            continue

        try:
            # Load ECG header and annotations
            ecg_header = wfdb.rdheader(ecg_path)
            fs_ecg = ecg_header.fs

            # Load bradycardia annotations (atr)
            try:
                brady_ann = wfdb.rdann(ecg_path, "atr")
                brady_samples = set(brady_ann.sample)
            except Exception:
                brady_samples = set()
                if verbose:
                    logger.warning(f"Infant {infant_num}: no bradycardia annotations.")

            # Load R-peak annotations (qrsc) to derive HR
            hr_estimates = []
            if derive_hr:
                try:
                    qrsc_ann = wfdb.rdann(ecg_path, "qrsc")
                    rpeaks = qrsc_ann.sample
                    # Compute instantaneous HR from RR intervals
                    rr_intervals = np.diff(rpeaks) / fs_ecg  # in seconds
                    inst_hr = 60.0 / rr_intervals  # bpm
                    # Clip to physiological range
                    inst_hr = np.clip(inst_hr, 60, 220)
                    hr_estimates = inst_hr.tolist()
                except Exception as e:
                    if verbose:
                        logger.warning(f"Infant {infant_num}: HR derivation failed: {e}")

            # Load respiration peak annotations to derive RR
            rr_estimates = []
            if derive_rr and os.path.exists(resp_path + ".hea"):
                try:
                    resp_ann = wfdb.rdann(resp_path, "resp")
                    resp_peaks = resp_ann.sample
                    resp_header = wfdb.rdheader(resp_path)
                    fs_resp = resp_header.fs
                    resp_intervals = np.diff(resp_peaks) / fs_resp  # seconds
                    inst_rr = 60.0 / resp_intervals  # breaths/min
                    inst_rr = np.clip(inst_rr, 10, 80)
                    rr_estimates = inst_rr.tolist()
                except Exception as e:
                    if verbose:
                        logger.warning(f"Infant {infant_num}: RR derivation failed: {e}")

            # Build a DataFrame for this infant
            # We use HR beats as the time reference
            n_beats = len(hr_estimates)
            if n_beats == 0:
                continue

            infant_df = pd.DataFrame()
            infant_df["patient_id"] = [f"PICS-{infant_num:02d}"] * n_beats
            infant_df["beat_index"] = range(n_beats)
            infant_df["heart_rate"] = hr_estimates

            # Align RR to HR length (they may differ)
            if rr_estimates:
                n_resp = len(rr_estimates)
                if n_resp >= n_beats:
                    infant_df["respiratory_rate"] = rr_estimates[:n_beats]
                else:
                    padded_rr = rr_estimates + [np.nan] * (n_beats - n_resp)
                    infant_df["respiratory_rate"] = padded_rr
            else:
                infant_df["respiratory_rate"] = np.nan

            # These signals are not in PICS
            infant_df["spo2"] = np.nan
            infant_df["temperature"] = np.nan
            infant_df["systolic_bp"] = np.nan
            infant_df["diastolic_bp"] = np.nan

            # Create label based on proximity to bradycardia annotations
            # A beat is labeled 1 if its sample index is near a bradycardia onset
            # (within 50 samples ≈ 0.1 s at 500 Hz — crude alignment)
            infant_df["deterioration_label"] = 0
            if brady_samples and derive_hr:
                try:
                    for brady_sample in brady_samples:
                        # Find beats within ±1 second of bradycardia onset
                        window_samples = fs_ecg  # 1 second
                        nearby_peaks = [
                            i for i, pk in enumerate(qrsc_ann.sample)
                            if abs(pk - brady_sample) < window_samples
                        ]
                        for idx in nearby_peaks:
                            if idx < n_beats:
                                infant_df.loc[idx, "deterioration_label"] = 1
                except Exception:
                    pass

            infant_df["data_source"] = "PICS_NEONATAL"
            infant_df["data_warning"] = "AUTHENTIC_NEONATAL_WAVEFORM_NOT_FOR_CLINICAL_USE"
            infant_df["clinical_event"] = infant_df["deterioration_label"].apply(
                lambda x: "bradycardia" if x == 1 else "none"
            )

            all_infants.append(infant_df)

            if verbose:
                n_events = infant_df["deterioration_label"].sum()
                logger.info(
                    f"  Infant {infant_num:02d}: "
                    f"{n_beats} beats, "
                    f"{n_events} bradycardia-labeled beats "
                    f"({n_events / n_beats * 100:.1f}%)"
                )

        except Exception as e:
            logger.error(f"Error loading infant {infant_num}: {e}")
            continue

    if not all_infants:
        raise ValueError(
            "No PICS data could be loaded. "
            "Check that WFDB files are present in the data directory."
        )

    combined = pd.concat(all_infants, ignore_index=True)

    if verbose:
        logger.info(f"PICS: loaded {combined['patient_id'].nunique()} infants")
        logger.info(f"PICS: total beats: {len(combined):,}")

    return combined


