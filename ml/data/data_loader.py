def load_synthetic_data(
    data_dir: str,
    verbose: bool = True,
) -> pd.DataFrame:
    """
    Load pre-generated synthetic NICU vital sign data.

    ⚠️  SYNTHETIC DATA — NOT FOR CLINICAL USE ⚠️

    Parameters
    ----------
    data_dir : str
        Directory containing synthetic_nicu_vitals.csv.
    verbose : bool
        Whether to log progress.

    Returns
    -------
    pd.DataFrame
        Synthetic vital sign data with all standard columns.
    """
    csv_path = os.path.join(data_dir, "synthetic_nicu_vitals.csv")

    if not os.path.exists(csv_path):
        logger.warning(
            f"Synthetic data not found at {csv_path}. "
            f"Run ml/data/synthetic_generator.py first."
        )
        raise FileNotFoundError(
            f"Synthetic data not found: {csv_path}. "
            f"Generate it with: python ml/data/synthetic_generator.py"
        )

    df = pd.read_csv(csv_path, parse_dates=["timestamp"])

    if verbose:
        logger.info(f"⚠️  Loaded SYNTHETIC data: {csv_path}")
        logger.info(f"    Patients: {df['patient_id'].nunique()}")
        logger.info(f"    Records:  {len(df):,}")
        logger.info("    This is NOT real patient data.")

    return df


# ─────────────────────────────────────────────────────────────────────────────
# UNIFIED LOADER
# ─────────────────────────────────────────────────────────────────────────────

def load_dataset(
    source: str,
    data_dir: str,
    max_patients: Optional[int] = None,
    verbose: bool = True,
) -> pd.DataFrame:
    """
    Unified dataset loader.

    Parameters
    ----------
    source : str
        One of: 'cinc2019', 'pics', 'synthetic'
    data_dir : str
        Path to the data directory for the selected source.
    max_patients : int, optional
        Limit (only for cinc2019).
    verbose : bool
        Log progress.

    Returns
    -------
    pd.DataFrame
        Standardized DataFrame for the selected source.
    """
    source = source.lower().strip()

    if source == "cinc2019":
        return load_cinc2019(data_dir, max_patients=max_patients, verbose=verbose)
    elif source == "pics":
        return load_pics_database(data_dir, verbose=verbose)
    elif source == "synthetic":
        return load_synthetic_data(data_dir, verbose=verbose)
    else:
        raise ValueError(
            f"Unknown source '{source}'. "
            f"Choose from: 'cinc2019', 'pics', 'synthetic'"
        )


# ─────────────────────────────────────────────────────────────────────────────
# DATASET AVAILABILITY CHECK
# ─────────────────────────────────────────────────────────────────────────────

def check_data_availability(base_data_dir: str) -> dict:
    """
    Check which datasets are available in the data directory.

    Parameters
    ----------
    base_data_dir : str
        Root data directory (e.g., data/).

    Returns
    -------
    dict
        Availability status for each dataset.
    """
    status = {
        "cinc2019": {
            "available": False,
            "path": os.path.join(base_data_dir, "raw", "challenge2019"),
            "note": "Download from: https://physionet.org/content/challenge-2019/1.0.0/",
        },
        "pics": {
            "available": False,
            "path": os.path.join(base_data_dir, "raw", "picsdb"),
            "note": "Download from: https://physionet.org/content/picsdb/1.0.0/",
        },
        "synthetic": {
            "available": False,
            "path": os.path.join(base_data_dir, "synthetic"),
            "note": "Generate with: python ml/data/synthetic_generator.py",
        },
    }

    # Check CinC 2019
    cinc_dir = status["cinc2019"]["path"]
    if os.path.isdir(cinc_dir):
        psv_files = glob.glob(os.path.join(cinc_dir, "*.psv"))
        if psv_files:
            status["cinc2019"]["available"] = True
            status["cinc2019"]["n_files"] = len(psv_files)

    # Check PICS
    pics_dir = status["pics"]["path"]
    if os.path.isdir(pics_dir):
        hea_files = glob.glob(os.path.join(pics_dir, "*.hea"))
        if hea_files:
            status["pics"]["available"] = True
            status["pics"]["n_files"] = len(hea_files)

    # Check synthetic
    syn_dir = status["synthetic"]["path"]
    syn_csv = os.path.join(syn_dir, "synthetic_nicu_vitals.csv")
    if os.path.exists(syn_csv):
        status["synthetic"]["available"] = True

    # Print report
    print("\n" + "=" * 55)
    print("NeoNatal Watch AI -- Dataset Availability Check")
    print("=" * 55)
    for name, info in status.items():
        avail = "[AVAILABLE]" if info["available"] else "[NOT FOUND]"
        print(f"\n[{name.upper()}]  {avail}")
        print(f"  Path: {info['path']}")
        if not info["available"]:
            print(f"  How to get: {info['note']}")
        else:
            if "n_files" in info:
                print(f"  Files found: {info['n_files']}")
    print("=" * 55 + "\n")

    return status


