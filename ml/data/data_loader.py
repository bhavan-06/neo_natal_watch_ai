"""
=============================================================================
NeoNatal Watch AI — Dataset Loader
=============================================================================

Loads and standardizes data from:

1. PhysioNet CinC Challenge 2019 (primary — adult ICU sepsis, open access)
   URL: https://physionet.org/content/challenge-2019/1.0.0/
   Label: SepsisLabel (binary per-timestep)

2. PICS Database (supplemental — 10 preterm infants, open access)
   URL: https://physionet.org/content/picsdb/1.0.0/
   Label: Bradycardia annotations (derived)

3. Synthetic Data (always available — no access required)
   Generated by: ml/data/synthetic_generator.py

IMPORTANT:
  - CinC 2019 data is ADULT ICU data, not neonatal.
  - It is used as a reference dataset for prototype development.
  - All outputs from models trained on this data must clearly state:
    "Trained on adult ICU reference data (CinC 2019). Not neonatal data."
=============================================================================
"""

